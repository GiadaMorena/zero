const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),path=require('path');
const root=process.argv[2]||path.resolve(__dirname,'..'),ts=require(root+'/node_modules/typescript');
const scope={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(root+'/src/lib/upcomingPayments.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,scope);
const {nextRenewal,upcomingPayments}=scope.exports;
const sub=(date,frequency='mese',cost=10,active=true)=>({id:date,name:date,date,frequency,cost,active});
const now=new Date(2026,9,9,23);
const parts=date=>[date.getFullYear(),date.getMonth()+1,date.getDate()];
assert.deepEqual(parts(nextRenewal(sub('1 gennaio'),now)),[2026,11,1]);
assert.deepEqual(parts(nextRenewal(sub('9 gennaio'),now)),[2026,10,9]);
assert.deepEqual(parts(nextRenewal(sub('1 gennaio','anno'),now)),[2027,1,1]);
assert.deepEqual(parts(nextRenewal(sub('31 gennaio'),new Date(2026,1,1))),[2026,2,28]);
assert.deepEqual(parts(nextRenewal(sub('29 febbraio','anno'),new Date(2028,0,1))),[2028,2,29]);
assert.deepEqual(parts(nextRenewal(sub('31/12/2020'),new Date(2026,11,31))),[2026,12,31]);
assert.deepEqual(parts(nextRenewal(sub('2024-10-10','anno'),now)),[2026,10,10]);
for(const date of ['0 gennaio','32 gennaio','12 sconosciuto','Mensile','1/13'])assert.equal(nextRenewal(sub(date),now),null);
const result=upcomingPayments([sub('10 ottobre','mese',.1),sub('9 ottobre','mese',.2),sub('9 ottobre','anno',999,false),sub('Mensile'),sub('10 novembre','anno',999)],now);
assert.equal(result.total,.3);assert.equal(result.undated,1);assert.equal(result.within30[0].days,0);assert.equal(result.within30.length,2);
assert.equal(upcomingPayments([],now).total,0);
console.log('Renewal ordering, inactive exclusion, annual/monthly rollover, leap years, month-end clamping, missing dates and cents precision passed');
assert.equal(upcomingPayments([sub("1 febbraio")],new Date(2026,1,1)).within30.length,2);
